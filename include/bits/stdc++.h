// bits/stdc++.h - a GCC extension, recreated for Apple clang.
//
// Codeforces, ECPC and ICPC all judge on GCC, where this header exists and
// pulls in the whole standard library at once. Apple's clang ships no such
// header, so code copied from any editorial fails to compile on this Mac.
//
// This file is that header, written out by hand. tools/judge.py passes
// -I include/ so every solution in this repo compiles locally exactly as it
// will on the judge. Nothing here is a dependency to install.

